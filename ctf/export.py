"""Export a policy `.npz` to a single self-contained `model.py` submission.

The generated file inlines the verbatim source of `ctf/features.py`, embeds the
weights and normalization as zlib-compressed base64 float32, and runs the
forward pass in numpy (single-threaded BLAS) with preallocated buffers. It needs
only the standard library and numpy, and works on Python 3.9+.

    python -m ctf.export POLICY.npz OUT.py [--decode greedy|sample]
"""

