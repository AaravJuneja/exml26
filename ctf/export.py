def _source_text():
    return Path(features.__file__).read_text(encoding="utf-8")


def _pack(arrays):
    raw = b"".join(np.ascontiguousarray(a, dtype="<f4").tobytes() for a in arrays)
    text = base64.b64encode(zlib.compress(raw, 9)).decode("ascii")
    return "\n".join(text[i:i + 100] for i in range(0, len(text), 100))


def render(policy_path, *, decode="greedy"):
    """Source text of the standalone model for `policy_path`."""
    if decode not in DECODES:
        raise ValueError(f"decode must be one of {DECODES}, got {decode!r}")
    actor, _ = load_policy(policy_path)
    arrays = [actor.obs_mean.astype(np.float32), actor.obs_std.astype(np.float32)]
    for w, b in actor.weights:
        arrays += [np.asarray(w, dtype=np.float32), np.asarray(b, dtype=np.float32)]
    if not np.all(actor.obs_std > 0):
        raise ValueError("obs_std must be positive")
    if not all(np.all(np.isfinite(a)) for a in arrays):
        raise ValueError("policy contains non-finite values")
    if arrays[-1].shape[0] != sum(HEAD_SIZES):
        raise ValueError("last layer does not match the action heads")

    source = _source_text()
    if "from __future__" in source:
        raise ValueError("features.py cannot be inlined after other statements")
    if "_mx_" in source.lower():
        raise ValueError("features.py uses the reserved _mx_ prefix")
    digest = hashlib.sha256(Path(policy_path).read_bytes()).hexdigest()
    layers = " -> ".join(str(w.shape[0]) for w, _ in actor.weights) + f" -> {arrays[-1].shape[0]}"
    header = _HEADER.format(source=Path(policy_path).name, digest=digest, layers=layers,
                            decode=decode)
    body = _BODY.format(decode=decode, head_sizes=tuple(HEAD_SIZES),
                        shapes=[tuple(a.shape) for a in arrays], blob=_pack(arrays))
    return header + FEATURES_BEGIN + source.rstrip("\n") + "\n" + FEATURES_END + body


def export(policy_path, out_path, *, decode="greedy"):
    text = render(policy_path, decode=decode)
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8")
    return out_path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("policy")
    parser.add_argument("out")
    parser.add_argument("--decode", choices=DECODES, default="greedy")
    args = parser.parse_args(argv)
    path = export(args.policy, args.out, decode=args.decode)
    print(f"wrote {path} ({path.stat().st_size / 1024:.0f} KiB, decode={args.decode})")


if __name__ == "__main__":
    main()
